// Command gen writes throwaway provider credentials and a gateway config for the end-to-end
// test into a directory (default .e2e), which docker-compose.e2e.yml mounts into the
// gateway. The config points APNs and FCM at the fakes the test serves on the host, and gives
// the web app a fresh VAPID key. The keys are generated on every run and never committed.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/parkerbrown98/gotalk-gateway/internal/providers/providertest"
)

// fakesHost is how the gateway container reaches the test process.
const fakesHost = "http://host.docker.internal"

const config = `# Generated by internal/e2e/gen for the end-to-end test. Do not edit.
apps:
  - id: gotalk
    name: Gotalk
    ios:
      bundle_id: app.example.gotalk
      apns:
        team_id: TEAM123456
        key_id: KEY1234567
        private_key_file: /etc/gotalk-gateway/e2e/apns.p8
        production_url: {{host}}:18081
        sandbox_url: {{host}}:18081
    android:
      package_name: app.example.gotalk
      fcm:
        service_account_file: /etc/gotalk-gateway/e2e/fcm.json
        endpoint: {{host}}:18082
    web:
      vapid_public_key: {{vapid_public_key}}
      vapid:
        private_key_file: /etc/gotalk-gateway/e2e/vapid.key
        subject: mailto:ops@gateway.example
`

func main() {
	dir := ".e2e"
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	if err := run(dir); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func run(dir string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil { //nolint:gosec // the gateway container's user reads it
		return err
	}
	p8, _ := providertest.NewAPNsKey()
	sa, _ := providertest.NewServiceAccount("e2e-project", fakesHost+":18082/token")
	vapidPrivate, vapidPublic := providertest.NewVAPIDKey()
	cfg := strings.NewReplacer("{{host}}", fakesHost, "{{vapid_public_key}}", vapidPublic).Replace(config)
	files := map[string][]byte{
		"apns.p8":     p8,
		"fcm.json":    sa,
		"vapid.key":   []byte(vapidPrivate),
		"config.yaml": []byte(cfg),
	}
	for name, data := range files {
		// World-readable so the container's non-root user can read the test-only keys.
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil { //nolint:gosec // throwaway test keys
			return err
		}
	}
	fmt.Println("wrote end-to-end credentials to", dir)
	return nil
}
